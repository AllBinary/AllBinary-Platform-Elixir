  def jm_antiTan(this, p_dx, p_dy) do
    JR.method(fn ->
      _ = this
      f = JR.frame()
      _ = f
      JR.lset(f, :dx, p_dx)
      JR.lset(f, :dy, p_dy)
        JR.lset(f, :MAX_VALUE, (J.Integer.jstatic_MAX_VALUE()))
        JR.lset(f, :MIN_VALUE, (J.Integer.jstatic_MIN_VALUE()))
        JR.lset(f, :ratio, (JR.int64(JR.lget(f, :MAX_VALUE) - 1)))
        if (JR.lget(f, :dy) != 0) do
            JR.lset(f, :dxl, (JR.lget(f, :dx)))
            JR.lset(f, :ratio, div(JR.int64(JR.get(this, :SCALE) * JR.lget(f, :dxl)), JR.lget(f, :dy)))
            if ((JR.lget(f, :dx) <= 0) && (JR.lget(f, :dy) < 0)) do
                JR.lset(f, :ratio, JR.call(JR.get(this, :mathUtil), :jm_abslong, [JR.lget(f, :ratio)]))
            end
        end
        if (((JR.lget(f, :dx) >= 0) && (JR.lget(f, :dy) < 0))) do
            JR.lset(f, :index, 180)
            JR.jfor(fn -> (JR.lget(f, :index) > 90) end, fn -> JR.lpostinc(f, :index, -1) end, fn ->
                if (JR.lget(f, :ratio) <= JR.aget(JR.get(this, :noDecimalTan), JR.lget(f, :index))) do
                    if (JR.lget(f, :ratio) > JR.aget(JR.get(this, :noDecimalTan), JR.int32(JR.lget(f, :index) - 1))) do
                        throw({:jreturn, (JR.int16(JR.lget(f, :index)))})
                    else
                        if ((JR.aget(JR.get(this, :noDecimalTan), JR.int32(JR.lget(f, :index) - 1)) == JR.lget(f, :MAX_VALUE)) && (JR.lget(f, :ratio) > JR.lget(f, :MIN_VALUE))) do
                        throw({:jreturn, (JR.int16(JR.lget(f, :index)))})
                    end
                    end
                end
            end)
        else
            if (((JR.lget(f, :dx) < 0) && (JR.lget(f, :dy) <= 0))) do
            JR.lset(f, :index, 270)
            JR.jfor(fn -> (JR.lget(f, :index) > 180) end, fn -> JR.lpostinc(f, :index, -1) end, fn ->
                if ((JR.lget(f, :ratio) < JR.aget(JR.get(this, :noDecimalTan), JR.lget(f, :index))) && (JR.lget(f, :ratio) >= JR.aget(JR.get(this, :noDecimalTan), JR.int32(JR.lget(f, :index) - 1)))) do
                    throw({:jreturn, (JR.int16(JR.lget(f, :index)))})
                end
            end)
        else
            if (((JR.lget(f, :dx) < 0) && (JR.lget(f, :dy) > 0))) do
            JR.lset(f, :index, (JR.int32(JR.alength(JR.get(this, :noDecimalTan)) - 1)))
            JR.jfor(fn -> (JR.lget(f, :index) > 270) end, fn -> JR.lpostinc(f, :index, -1) end, fn ->
                if (JR.lget(f, :ratio) < JR.aget(JR.get(this, :noDecimalTan), JR.lget(f, :index))) do
                    if (JR.lget(f, :ratio) >= JR.aget(JR.get(this, :noDecimalTan), JR.int32(JR.lget(f, :index) - 1))) do
                        throw({:jreturn, (JR.int16(JR.lget(f, :index)))})
                    else
                        if ((JR.aget(JR.get(this, :noDecimalTan), JR.int32(JR.lget(f, :index) - 1)) == JR.lget(f, :MAX_VALUE)) && (JR.lget(f, :ratio) >= JR.lget(f, :MIN_VALUE))) do
                        throw({:jreturn, (JR.int16(JR.lget(f, :index)))})
                    end
                    end
                end
            end)
        else
            if (((JR.lget(f, :dx) >= 0) && (JR.lget(f, :dy) >= 0))) do
            JR.lset(f, :index, 90)
            JR.jfor(fn -> (JR.lget(f, :index) > 0) end, fn -> JR.lpostinc(f, :index, -1) end, fn ->
                if ((JR.lget(f, :ratio) < JR.aget(JR.get(this, :noDecimalTan), JR.lget(f, :index))) && (JR.lget(f, :ratio) >= JR.aget(JR.get(this, :noDecimalTan), JR.int32(JR.lget(f, :index) - 1)))) do
                    throw({:jreturn, (JR.int16(JR.lget(f, :index)))})
                end
            end)
        end
        end
        end
        end
        JR.lset(f, :stringBuffer, StringMaker.jnew())
        JR.call(JR.lget(f, :stringBuffer), :jm_append, ["Invalid Ratio: "])
        JR.call(JR.lget(f, :stringBuffer), :jm_appendlong, [JR.lget(f, :ratio)])
        JR.call(JR.lget(f, :stringBuffer), :jm_append, [JR.get(CommonSeps.jm_getInstance(), :SPACE)])
        JR.call(JR.lget(f, :stringBuffer), :jm_append, [JR.get(PositionStrings.jm_getInstance(), :DX_LABEL)])
        JR.call(JR.lget(f, :stringBuffer), :jm_appendint, [JR.lget(f, :dx)])
        JR.call(JR.lget(f, :stringBuffer), :jm_append, [JR.get(CommonSeps.jm_getInstance(), :SPACE)])
        JR.call(JR.lget(f, :stringBuffer), :jm_append, [JR.get(PositionStrings.jm_getInstance(), :DX_LABEL)])
        JR.call(JR.lget(f, :stringBuffer), :jm_appendint, [JR.lget(f, :dy)])
        throw({:jexception, JR.exception("Exception", JR.call(JR.lget(f, :stringBuffer), :jm_toString, []))})
    end)
  end


